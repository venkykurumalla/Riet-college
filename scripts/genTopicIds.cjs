// Writes src/data/crtTopicIds.ts: topic ids per year, read from src/data/chapters/*.json.
// Lets the progress service count topics without importing the (large) chapter data.
// Re-run after adding or removing a chapter: node scripts/genTopicIds.cjs
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'src', 'data', 'chapters');
const byYear = { 1: [], 2: [], 3: [], 4: [] };
fs.readdirSync(dir).filter(f => f.endsWith('.json')).forEach(f => {
  const d = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  byYear[d.yearId].push([d.topicNumber, d.id]);
});
const body = Object.entries(byYear)
  .map(([y, rows]) => `  ${y}: [\n${rows.sort((a, b) => a[0] - b[0]).map(r => `    '${r[1]}'`).join(',\n')}\n  ]`)
  .join(',\n');
fs.writeFileSync(
  path.join(__dirname, '..', 'src', 'data', 'crtTopicIds.ts'),
  `// Generated by scripts/genTopicIds.cjs - do not edit by hand.\nimport { CRTYearId } from '../types/crtTypes';\n\nexport const CRT_TOPIC_IDS: Record<CRTYearId, string[]> = {\n${body}\n};\n`
);
console.log(Object.fromEntries(Object.entries(byYear).map(([y, r]) => [y, r.length])));
